    // ==================== Partition C: Defect-Targeted (Bridge Method) ====================

    @Test(timeout = 4000)
    public void testMatchesWithBridgeMethod() throws Exception {
        // Simulate the defect: generic method vs bridge method
        Method genericMethod = GenericBase.class.getMethod("foo", Object.class);
        Method bridgeMethod = Concrete.class.getMethod("foo", Object.class); // synthetic bridge
        Method actualMethod = Concrete.class.getMethod("foo", String.class); // actual method

        Object mock = new Object();
        SimpleInvocation wantedInv = new SimpleInvocation(mock, genericMethod, (Object) "test");
        InvocationMatcher im = new InvocationMatcher(wantedInv);

        // Actual invocation uses the bridge method (as generated by Java)
        SimpleInvocation actualInv = new SimpleInvocation(mock, bridgeMethod, (Object) "test");
        // The bug: hasSameMethod returns false because Method.equals fails for bridge methods
        // Expected: matches should return true (they are semantically the same)
        assertTrue("Bridge method should match generic method", im.matches(actualInv));

        // Also test with the actual method (non-bridge)
        SimpleInvocation actualInv2 = new SimpleInvocation(mock, actualMethod, (Object) "test");
        assertTrue("Actual method should match generic method", im.matches(actualInv2));
    }

    @Test(timeout = 4000)
    public void testHasSimilarMethodWithBridge() throws Exception {
        Method genericMethod = GenericBase.class.getMethod("foo", Object.class);
        Method bridgeMethod = Concrete.class.getMethod("foo", Object.class);
        Object mock = new Object();
        SimpleInvocation wantedInv = new SimpleInvocation(mock, genericMethod, (Object) "test");
        InvocationMatcher im = new InvocationMatcher(wantedInv);

        SimpleInvocation candidate = new SimpleInvocation(mock, bridgeMethod, (Object) "test");
        // hasSimilarMethod should return true because method names match, mock same, unverified, and not overloaded
        assertTrue(im.hasSimilarMethod(candidate));
    }

