    private static Method getMethod(String name, Class<?>... paramTypes) {
        try {
            return Object.class.getMethod(name, paramTypes);
        } catch (NoSuchMethodException e) {
            throw new RuntimeException(e);
        }
    }

    // Custom CapturesArguments matcher for testing
    private static class CapturingMatcher implements Matcher, CapturesArguments {
        Object capturedValue;

        @Override
        public boolean matches(Object item) {
            return true;
        }

        @Override
        public void describeTo(org.hamcrest.Description description) {
            description.appendText("capturing");
        }

        @Override
        public void captureFrom(Object argument) {
            capturedValue = argument;
        }

        @Override
        public void _dont_implement_Matcher___instead_extend_BaseMatcher_() {
            // no-op
        }
    }
