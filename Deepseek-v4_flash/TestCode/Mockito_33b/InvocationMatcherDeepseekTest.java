    @Test(timeout = 4000)
    public void testHasSimilarMethodOverloadedButSameArgs() throws Exception {
        // Create two methods with same name but different parameter types
        Method m1 = getMethod("equals", Object.class);
        Method m2 = getMethod("equals", Object.class); // same signature, not overloaded
        Object mock = new Object();
        SimpleInvocation inv = new SimpleInvocation(mock, m1, (Object) "a");
        InvocationMatcher im = new InvocationMatcher(inv);
        SimpleInvocation candidate = new SimpleInvocation(mock, m2, (Object) "a");
        // hasSameMethod returns true, so overloadedButSameArgs is false -> returns true
        assertTrue(im.hasSimilarMethod(candidate));
    }

    @Test(timeout = 4000)
    public void testHasSimilarMethodOverloadedDifferentArgs() throws Exception {
        // Use methods with same name but different parameter types (overloaded)
        Method m1 = String.class.getMethod("valueOf", int.class);
        Method m2 = String.class.getMethod("valueOf", long.class);
        Object mock = new Object();
        SimpleInvocation inv = new SimpleInvocation(mock, m1, 1);
        InvocationMatcher im = new InvocationMatcher(inv);
        SimpleInvocation candidate = new SimpleInvocation(mock, m2, 1L);
        // hasSameMethod false, but safelyArgumentsMatch should return false because args differ
        assertFalse(im.hasSimilarMethod(candidate));
    }

