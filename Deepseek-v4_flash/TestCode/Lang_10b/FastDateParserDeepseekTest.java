    /* [Branch & Defect Analysis Matrix]
     * 
     * Defect LANG-831: Pattern "M E,3  Tue" (month text, day-of-week text, then comma+space+number+space+text)
     *   Input "M E,3  Tue" should cause parse failure (null/ParseException), but buggy version returns a date.
     *   Root cause: The regex generated by NumberStrategy and TextStrategy may allow greedy matching across fields.
     * 
     * Branches targeted:
     * - Constructor: valid pattern, invalid pattern (no match), quoted patterns, empty pattern
     * - init(): loop over pattern matcher, addRegex return value (true/false), collector build
     * - parse(String): null return, JAPANESE_IMPERIAL locale branch
     * - parse(String,ParsePosition): matcher.lookingAt() success/failure, strategy loop, setCalendar
     * - getDisplayNames: ERA, DAY_OF_WEEK, AM_PM, MONTH, default exception
     * - toArray: null key throws IllegalArgumentException
     * - adjustYear: boundaries (trial < thisYear+20, else trial-100)
     * - isNextNumber: nextStrategy null/not null, isNumber
     * - getFieldWidth: length of currentFormatField
     * - escapeRegex: whitespace, special chars, quotes, unquote logic
     * - Strategy impls: CopyQuotedStrategy, TextStrategy (binarySearch fail), NumberStrategy, ABBREVIATED_YEAR_STRATEGY, TimeZoneStrategy
     * - TimeZoneStrategy: GMT offsets, named timezones, daylight saving
     * - Serialization: readObject triggers init
     * - Object contract: equals, hashCode, toString
     */
    
