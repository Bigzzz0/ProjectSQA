    // Helper to create a test generator with a StringWriter
    private ToXmlGenerator createGenerator(StringWriter sw) throws IOException {
        IOContext ctxt = new IOContext(
                new com.fasterxml.jackson.core.json.JsonFactory()._getBufferFactory(),
                null, null, false, null);
        XMLStreamWriter xsw = new com.ctc.wstx.sr.StreamWriterImpl(
                new com.ctc.wstx.api.WriterConfig(), sw, "UTF-8");
        return new ToXmlGenerator(ctxt, 0, 0, null, xsw);
    }

    // Helper to create a generator with a ByteArrayOutputStream
