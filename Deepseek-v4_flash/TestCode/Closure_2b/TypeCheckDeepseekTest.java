    /**
     * Partition A: Core Functional Logic & State Transitions
     * Tests basic type checking of function calls and constructors.
     */
    @Test(timeout = 4000)
    public void testBasicFunctionCall() {
        String js = "/** @param {number} x @return {number} */ function f(x) { return x + 1; } f(3);";
        assertNoErrors(js);
    }

    @Test(timeout = 4000)
    public void testConstructorCall() {
        String js = "/** @constructor */ function Foo() {} var f = new Foo();";
        assertNoErrors(js);
    }

    @Test(timeout = 4000)
    public void testPropertyAccess() {
        String js = "/** @constructor */ function Foo() { this.x = 1; } var f = new Foo(); var y = f.x;";
        assertNoErrors(js);
    }

    @Test(timeout = 4000)
    public void testObjectLiteral() {
        String js = "var obj = {a: 1, b: 'two'};";
        assertNoErrors(js);
    }

    @Test(timeout = 4000)
    public void testAssignment() {
        String js = "var x = 5; x = 10;";
        assertNoErrors(js);
    }

    /**
     * Partition B: Boundary Value Analysis & Extremes
     */
    @Test(timeout = 4000)
    public void testNullPropertyAccess() {
        String js = "var x = null; var y = x.foo;";
        assertErrors(js, TypeCheck.TYPE_MISMATCH_WARNING);
    }

    @Test(timeout = 4000)
    public void testUnknownTypeProperty() {
        String js = "var x = unknownVar; var y = x.foo;";
        assertNoErrors(js); // Unknown types should not error
    }

    @Test(timeout = 4000)
    public void testEmptyFunctionCall() {
        String js = "/** @param {number=} x */ function f(x) {} f();";
        assertNoErrors(js);
    }

    @Test(timeout = 4000)
    public void testVarArgsFunction() {
        String js = "/** @param {...number} args */ function f(args) {} f(1,2,3);";
        assertNoErrors(js);
    }

    @Test(timeout = 4000)
    public void testMaxArgsFunction() {
        String js = "/** @param {number} a @param {number} b */ function f(a,b) {} f(1,2);";
        assertNoErrors(js);
    }

